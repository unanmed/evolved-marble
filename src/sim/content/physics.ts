/* ---------------------------------------------------------------------------
 * 碰撞分组位（D-27：单位级分组）
 *
 * `InteractionGroups` 为单个 `number`：高 16 位是**成员位**，低 16 位是**过滤掩码**；
 * 交互允许当且仅当 `((a >> 16) & b) != 0 && ((b >> 16) & a) != 0`。每个存活单位从
 * **确定性存活池**中领取一个**互异**的成员位掩码（见 `composite.ts` 的池枚举器），
 * 从而使同一单位各部件互斥、任意不同单位之间仍保持物理碰撞——不再按 id 取模复用位。
 * ------------------------------------------------------------------------- */

/** 成员位/过滤掩码字段的位宽（`InteractionGroups` 的每个字段各 16 位）。 */
export const GROUP_BIT_COUNT = 16;

/**
 * 每个存活单位领取的成员位数。
 *
 * 采用**互异的 2 位掩码**：两个等势掩码在位包含下互不包含，故任意不同单位至少共享一位
 * 可交互位；该选择使可容纳的存活单位数达到 `C(16, 2) = 120`，覆盖 10v10（20 单位）以上的
 * 目标规模。若改回 1 位则上限降为 16（低于目标规模）。
 */
export const GROUP_MEMBERSHIP_BITS_PER_UNIT = 2;

/**
 * 同时存活单位数上限（D-27）。
 *
 * 等于 16 位内全部 2 位子集的个数 `C(16, 2) = 120`；超过即**抛错**，绝不静默复用成员位。
 * 该字面量与 `composite.ts` 中按 `GROUP_BIT_COUNT × GROUP_MEMBERSHIP_BITS_PER_UNIT` 枚举出的
 * 池长由模块级一致性断言守护——一旦二者不符，导入即抛错（改每单位位数不会静默失配）。
 *
 * 注意：16 位成员字段是**本编码**的约束，**并非** Rapier 的单位数硬上限——Rapier 不要求
 * 每个单位占一位。
 */
export const GROUP_UNIT_CAPACITY = 120;

/** 允许与任意分组碰撞的过滤掩码（低 16 位，全 1）。 */
export const GROUP_MASK_ALL = 0xffff;

